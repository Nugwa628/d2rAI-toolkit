"""Regenerate `fns.py` (the engine functions D2R's scripts call) from a folder of `.particles`:

  cd tools && python -m hdkit.fx.lang.gen_fns <folder with .particles> [> hdkit/fx/lang/fns_data.py]

Per function: result type, call flags, whether it is a method, and which parameters are "immediate" (argument kind 0)."""
from __future__ import annotations

import collections
import sys
from pathlib import Path

from .isa import cb, reg_cls, reg_type, NONE
from .fns import split_mangled


def collect(root: Path) -> dict:
    from hdkit.formats import hd_particles as hp
    seen = collections.defaultdict(lambda: {"ret": collections.Counter(), "imm": collections.defaultdict(set),
                                            "method": False, "n": 0})
    for f in sorted(root.rglob("*.particles")):
        data = f.read_bytes()
        if not data:
            continue
        for s in cb.scripts(hp.ParticleFile(data)):
            for i in s.code:
                if i.op != 0x7B:
                    continue
                name = s.fn_names[i.imm[2]]
                e = seen[name]
                e["n"] += 1
                e["ret"][None if i.regs[0] == NONE else reg_type(i.regs[0])] += 1
                e["method"] = e["method"] or i.imm[1] >= 0
                for k, (kind, r) in enumerate(i.args):
                    e["imm"][k].add(kind & 8 == 0 and reg_cls(r) == 0)
    out = {}
    for name, e in sorted(seen.items()):
        _base, params, ctxs = split_mangled(name)
        ret = e["ret"].most_common(1)[0][0]
        imm = [k for k in range(len(params)) if e["imm"].get(k) == {True}]
        out[name] = (ret, imm, e["n"])
    return out


def main(argv=None) -> int:
    argv = sys.argv[1:] if argv is None else argv
    table = collect(Path(argv[0]))
    print('"""Generated by gen_fns.py from D2R\'s 2,206 .particles: {mangled name: (result type, immediate params, uses)}."""')
    print("FNS = {")
    for k, v in table.items():
        print(f"    {k!r}: {v!r},")
    print("}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
