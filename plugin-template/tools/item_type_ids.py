"""Item type ids a D2R mod must keep: check itemtypes.txt and write the plugin's item_type_ids.h.

D2R.exe tests some item types by number (``0x373890(item, type)`` with the type written into the code, build 93847).
If a mod's itemtypes.txt gives those codes other row numbers (for example because D2R's ``warl`` row at 67 was moved
to the end), D2R's rune test hits another type and the game crashes on picking up an item. See
knowledge/porting-classic-mods.md section 4.

Row ids are counted the way D2R counts them: every data row except rows whose first cell is ``Expansion``.

    python plugin-template/tools/item_type_ids.py <itemtypes.txt> [<out item_type_ids.h>]

Exit code 0 when every checked code has D2R's id, 1 when one differs or is missing (the header is still written,
with the mod's ids, so the plugin's startup self-check reports the same thing).
"""

from __future__ import annotations

import sys
from pathlib import Path

# code -> id in D2R 3.3 (both banks). The codes D2R.exe tests by number.
D2R_IDS: dict[str, int] = {
    "jewl": 58,
    "h2h": 68,
    "pelt": 73,
    "rune": 75,
    "hpot": 77,
    "apot": 81,
    "wpot": 82,
    "scha": 83,
    "mcha": 84,
    "gem4": 96,
}


def read_ids(text: str) -> dict[str, int]:
    """Map each itemtypes ``Code`` to its row id (rows counted as D2R does)."""
    lines = [line for line in text.splitlines() if line.strip("\t ") != ""]
    if not lines:
        raise ValueError("itemtypes.txt is empty")
    header = lines[0].split("\t")
    try:
        code_col = header.index("Code")
    except ValueError:
        raise ValueError("itemtypes.txt has no 'Code' column") from None
    ids: dict[str, int] = {}
    row = 0
    for line in lines[1:]:
        cells = line.split("\t")
        if cells[0] == "Expansion":
            continue
        code = cells[code_col].strip() if code_col < len(cells) else ""
        if code and code not in ids:
            ids[code] = row
        row += 1
    return ids


def check(ids: dict[str, int]) -> list[str]:
    """One message per checked code whose id is not D2R's."""
    problems = []
    for code, want in D2R_IDS.items():
        got = ids.get(code)
        if got is None:
            problems.append(f"{code}: missing (D2R expects id {want})")
        elif got != want:
            problems.append(f"{code}: id {got}, D2R expects {want}")
    return problems


def header(ids: dict[str, int]) -> str:
    """The C++ header for plugin-template/src/item_type_ids.h (missing codes get -1)."""
    entries = ", ".join(f'{{"{code}", {ids.get(code, -1)}}}' for code in D2R_IDS)
    return (
        "// The mod's itemtypes.txt ids of the item types D2R.exe tests by number (item_type_check.cpp).\n"
        "// GENERATED by plugin-template/tools/item_type_ids.py from the mod's built itemtypes.txt. Do not edit.\n"
        "#pragma once\n\n"
        "namespace item_type_ids {\n\n"
        "struct Entry {\n\tconst char* code;\n\tint id;\n};\n\n"
        f"inline constexpr Entry Mod[] = {{{entries}}};\n\n"
        "}  // namespace item_type_ids\n"
    )


def main(argv: list[str]) -> int:
    if len(argv) not in (2, 3):
        print(__doc__.strip().splitlines()[0])
        print("usage: item_type_ids.py <itemtypes.txt> [<out item_type_ids.h>]")
        return 2
    ids = read_ids(Path(argv[1]).read_text(encoding="latin-1"))
    if len(argv) == 3:
        Path(argv[2]).write_text(header(ids), encoding="utf-8", newline="\n")
    problems = check(ids)
    for p in problems:
        print(f"item type id: {p}")
    if not problems:
        print(f"item type ids ok: {len(D2R_IDS)} of {len(D2R_IDS)} as D2R")
    return 1 if problems else 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
